import "@testing-library/jest-dom/vitest";
import "fake-indexeddb/auto";

// jsdom lacks matchMedia (used for prefers-reduced-motion).
if (typeof window !== "undefined" && !window.matchMedia) {
  window.matchMedia = (query: string) =>
    ({
      matches: false,
      media: query,
      onchange: null,
      addListener() {},
      removeListener() {},
      addEventListener() {},
      removeEventListener() {},
      dispatchEvent: () => false,
    }) as MediaQueryList;
}
